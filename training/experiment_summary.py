"""Generate reproducible Markdown summaries from actual PRD training logs."""

import argparse
import ast
import json
import re
from pathlib import Path

def write_experiment_summary(log_path, reason, evaluation=None):
    """Write one summary per run; distinguish selection-time and final metrics."""
    log_path = Path(log_path).resolve()
    text = log_path.read_text()
    dataset_config = re.search(r'^test_dataset:\s*(\[.*\])', text, re.MULTILINE)
    expected = set(ast.literal_eval(dataset_config[1])) if dataset_config else set()
    epoch, evaluations, completed, selected = None, {}, {}, None
    for line in text.splitlines():
        match = re.search(r'Epoch\[(\d+)\] start!', line)
        if match:
            epoch = int(match[1])
        match = re.search(r'dataset:\s*(\S+)\s+step:\s*(\d+).*testing-metric, auc:', line)
        if match:
            values = {k: float(v) for k, v in re.findall(r'testing-metric, (\w+): ([0-9.eE+-]+)', line)}
            evaluations.setdefault(int(match[2]), {})[match[1]] = values
        if 'Checkpoint saved to' in line and '/test/avg/ckpt_best.pth' in line:
            # The average checkpoint is saved after the constituent test metrics.
            if evaluations and (not expected or set(evaluations[max(evaluations)]) == expected):
                selected = (epoch, max(evaluations), {k: dict(v) for k, v in evaluations[max(evaluations)].items()})
        match = re.search(r'Epoch\[(\d+)\] end with testing', line)
        if match and evaluations and (not expected or set(evaluations[max(evaluations)]) == expected):
            completed[int(match[1])] = (max(evaluations), evaluations[max(evaluations)])
    lines = ['<!-- generated by experiment_summary.py -->', '# ' + log_path.parent.name + ' 实验摘要', '',
             f'- 结束/事件原因：{reason}', f'- 训练日志：`{log_path}`',
             f'- 最后开始的 epoch：{epoch}；最后完整 epoch：{max(completed) if completed else "无"}',
             '- epoch 使用代码原始零基编号；平均最佳指按多集平均指标选出的单个 checkpoint，不是权重算术平均。', '']
    metadata = log_path.parent / 'run_metadata.json'
    if metadata.exists():
        info = json.loads(metadata.read_text())
        config = info.get('config', {})
        info = {k: v for k, v in info.items() if k != 'config'}
        info['training_config'] = {k: config[k] for k in ('train_batchSize', 'test_batchSize', 'manualSeed', 'optimizer', 'frame_num', 'data_root', 'clip_path', 'vae_path', 'nEpochs') if k in config}
        lines += ['## 运行配置', '', '```json', json.dumps(info, indent=2, ensure_ascii=False), '```', '']
    else:
        lines += ['运行元数据文件缺失；以下是日志中的原始配置证据：', '', '```text']
        keys = ('train_batchSize:', 'manualSeed:', 'train_dataset:', 'test_dataset:', 'probe:', 'residual:', 'encoder:', 'data_root:')
        lines += list(dict.fromkeys(l for l in text.splitlines() if l.startswith(keys))) + ['```', '']
    if selected:
        e, step, metrics = selected
        lines += ['## 同一平均最佳 checkpoint 的结果', '', f'选择时刻：Epoch {e}，global step {step}。', '',
                  f'权重：`{log_path.parent / "test/avg/ckpt_best.pth"}`', '',
                  '| 数据集 | AUC | AP | EER | Video AUC |', '|---|---:|---:|---:|---:|']
        for name, vals in metrics.items():
            lines.append('| ' + name + ' | ' + ' | '.join(f'{vals[k]:.8f}' if k in vals else '未记录' for k in ('auc','ap','eer','video_auc')) + ' |')
        lines += ['| 平均 | ' + ' | '.join(f'{sum(v[k] for v in metrics.values()) / len(metrics):.8f}' if all(k in v for v in metrics.values()) else '未记录' for k in ('auc','ap','eer','video_auc')) + ' |', '']
    else:
        lines += ['未在日志中找到平均最佳权重保存事件，不能推断其来源或成绩。', '']
    lines += ['## 各完整 epoch 末的测试结果', '', '| Epoch | Step | 平均 AUC |', '|---|---:|---:|']
    for e, (step, metrics) in sorted(completed.items()):
        lines.append(f'| {e} | {step} | {sum(v["auc"] for v in metrics.values()) / len(metrics):.8f} |')
    if evaluation:
        lines += ['', '## 后续独立评测原始报告', '', f'来源：`{evaluation}`', '', '```text', Path(evaluation).read_text(), '```']
    lines += ['', '## 解释边界', '', '以上为单次实验记录，不能据此证明机制或批大小的因果效果。未记录的指标不补造。', '']
    directory = log_path.parent
    directory.mkdir(parents=True, exist_ok=True)
    destination = directory / (log_path.parent.name + '_实验摘要.md')
    if destination.exists() and not destination.read_text().startswith('<!-- generated by experiment_summary.py -->'):
        raise FileExistsError(f'Refusing to overwrite a manually authored summary: {destination}')
    temporary = destination.with_suffix('.md.tmp')
    temporary.write_text('\n'.join(lines))
    temporary.replace(destination)
    return destination


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('log')
    parser.add_argument('--reason', required=True)
    parser.add_argument('--evaluation')
    args = parser.parse_args()
    print(write_experiment_summary(args.log, args.reason, args.evaluation))
